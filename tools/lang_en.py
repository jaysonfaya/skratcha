def to_en(s):
    import re
    if s in FULL:
        return FULL[s]
    stripped = s.strip()
    if stripped in FULL:
        return s.replace(stripped, FULL[stripped])
    out = s
    for de in sorted(PHRASES, key=len, reverse=True):
        out = re.sub(r"(?<![A-Za-z0-9])" + re.escape(de) + r"(?![A-Za-z])", PHRASES[de], out)
    return out


def write_header(path):
    def esc(t):
        return t.replace("\\", "\\\\").replace('"', '\\"')
    lines = ["// generated by tools/lang_en.py - do not edit", "#pragma once", "namespace skrlang {",
             "struct Pair { const char* de; const char* en; };", "static const Pair kFull[] = {"]
    for de, en in FULL.items():
        lines.append('    {"%s", "%s"},' % (esc(de), esc(en)))
    lines.append("};")
    lines.append("static const Pair kPhrases[] = {   // longest first")
    for de in sorted(PHRASES, key=len, reverse=True):
        lines.append('    {"%s", "%s"},' % (esc(de), esc(PHRASES[de])))
    lines.append("};")
    lines.append("} // namespace skrlang")
    open(path, "w").write("\n".join(lines) + "\n")


